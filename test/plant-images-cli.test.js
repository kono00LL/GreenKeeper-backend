const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { promisify } = require('node:util');
const { execFile } = require('node:child_process');
const Database = require('better-sqlite3');
const sharp = require('sharp');
const request = require('supertest');
const { initializeDatabase } = require('../src/database');
const { createApp } = require('../src/app');

const run = promisify(execFile);
const backend = path.resolve(__dirname, '..');

test('CLI checks without writes, backs up a legacy database, imports and serves WebP idempotently', async (t) => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'plant-images-cli-'));
  t.after(() => fs.rm(directory, { recursive: true, force: true }));
  const databasePath = path.join(directory, 'greenkeeper.sqlite');
  const db = new Database(databasePath);
  initializeDatabase(db);
  db.exec('DROP TABLE plant_images');
  db.prepare('INSERT INTO plants (id, scientific_name, name_zh) VALUES (?, ?, ?)').run('test', 'Testus plantus', '测试植物');
  db.close();
  await fs.mkdir(path.join(directory, 'incoming'));
  await fs.writeFile(path.join(directory, 'incoming', 'plant.jpg'), await sharp({ create: { width: 1500, height: 1000, channels: 3, background: '#12ab34' } }).jpeg().toBuffer());
  const manifestPath = path.join(directory, 'images.json');
  const manifest = [{ plantId: 'test', scientificName: 'Testus plantus', nameZh: '测试植物', file: 'incoming/plant.jpg', sourceName: 'Self', sourceUrl: 'https://example.com/plant', license: 'CC0', attribution: 'Test author', checkedAt: '2026-11-03T00:00:00.000Z' }];
  await fs.writeFile(manifestPath, JSON.stringify(manifest));
  const env = { ...process.env, DATA_DIRECTORY: directory, PLANT_IMAGES_MANIFEST: manifestPath, PLANT_IMAGES_DIRECTORY: directory, IMAGE_STORAGE: 'local' };
  const cli = async (...args) => JSON.parse((await run(process.execPath, ['src/plants/import-images-cli.js', ...args], { cwd: backend, env })).stdout);
  const before = await fs.readFile(databasePath);
  const checked = await cli('--check');
  assert.equal(checked.valid, true);
  assert.equal(checked.ready, 1);
  assert.deepEqual(await fs.readFile(databasePath), before);
  assert.equal((await fs.readdir(directory)).includes('uploads'), false);
  assert.equal((await fs.readdir(directory)).includes('backups'), false);
  const applied = await cli('--apply');
  assert.equal(applied.inserted, 1);
  assert.equal(applied.integrityCheck, 'ok');
  const backup = new Database(applied.backupPath, { readonly: true });
  assert.equal(backup.prepare("SELECT name FROM sqlite_master WHERE name = 'plant_images'").get(), undefined);
  assert.equal(backup.pragma('integrity_check')[0].integrity_check, 'ok');
  backup.close();
  const imported = new Database(databasePath);
  t.after(() => imported.close());
  const image = imported.prepare('SELECT * FROM plant_images').get();
  assert.equal(image.width, 1200);
  assert.equal(image.height, 800);
  const app = createApp({ db: imported, uploadDirectory: path.join(directory, 'uploads') });
  const detail = await request(app).get('/plants/test');
  const response = await request(app).get(detail.body.plant.coverImage.url);
  assert.equal(response.status, 200);
  assert.match(response.headers['content-type'], /image\/webp/);
  const repeated = await cli('--apply');
  assert.equal(repeated.unchanged, 1);
  assert.equal((await fs.readdir(path.join(directory, 'uploads'))).length, 1);
  assert.equal(imported.prepare('SELECT COUNT(*) AS n FROM plant_images').get().n, 1);
  await fs.writeFile(path.join(directory, 'incoming', 'plant.jpg'), await sharp({ create: { width: 50, height: 30, channels: 3, background: '#ff0000' } }).jpeg().toBuffer());
  await assert.rejects(cli('--apply'), /Command failed/);
  await assert.rejects(cli('--apply', '--replace'), /allow-small/);
  assert.equal(imported.prepare('SELECT storage_key FROM plant_images').get().storage_key, image.storage_key);
  const replacement = await cli('--apply', '--replace', '--allow-small');
  assert.equal(replacement.replaced, 1);
  const files = await fs.readdir(path.join(directory, 'uploads'));
  assert.equal(files.length, 1);
  assert.equal(files.includes(image.storage_key), false);
  const replaced = ['--check', '--apply'];
  await assert.rejects(cli(...replaced), /Usage:/);
  await fs.writeFile(manifestPath, '{invalid json');
  await assert.rejects(cli('--check'));
  assert.equal(imported.prepare('SELECT COUNT(*) AS n FROM plant_images').get().n, 1);
});
